//! NIST P-384 (secp384r1) ECDSA signature verification, built on
//! [`crate::ecc`]'s shared point arithmetic and verify algorithm. See
//! [`crate::p256`]'s module doc for the domain-parameter cross-checking
//! method and why [`ecc::CurveParams`] is rebuilt (cheaply) on every call
//! rather than cached.

use crate::ecc::{self, CurveParams, Point};

pub use crate::ecc::EcdsaError;

/// Coordinate/field size in bytes.
const BYTE_LEN: usize = 48;

